"""Reproducible synthetic evaluation for world-projection-3x3.

Run: python3 full_science.py [optional-results-path]
The emitted JSON records the fixed seeds, report data, metrics, Python version,
and code-bound seal. All values are generated by this package's toy simulator.
"""
import json
import math
import pathlib
import platform
import random
import sys

from bubble import Bubble
from calibrator import Calibrator
from nervous import noisy, rand_field
from observer import Observer, wilson
from optimizer3x3 import DEFAULT_SPLIT_SEEDS, DEFAULT_WORLD_SEEDS, optimise
from passport3x3 import code_hashes, headline_allowed, seal
from sweep3x3 import full_sweep


def json_safe(value):
    """Convert non-finite floats to explicit strings for strict JSON."""
    if isinstance(value, dict):
        return {str(k): json_safe(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [json_safe(v) for v in value]
    if isinstance(value, float) and not math.isfinite(value):
        if math.isnan(value):
            return "NaN"
        return "Infinity" if value > 0 else "-Infinity"
    return value


def evaluate_assumed(bubble, probes, labels, random_fields, tau, f_hz):
    """Memoryless held-out classifier evaluation; no world actions occur."""
    if len(probes) != len(labels) or not probes or not random_fields:
        raise ValueError("held-out data must be non-empty and aligned")
    accepted = 0
    correct = 0
    for field, label in zip(probes, labels):
        decision, response, _ = bubble.decide_shadow(
            field, tau=tau, freq_hz=f_hz)
        if decision == "accept":
            accepted += 1
            correct += int(response == bubble.system.RESPONSE_NAMES[label])
    false_accepts = sum(
        1 for field in random_fields
        if bubble.decide_shadow(field, tau=tau, freq_hz=f_hz)[0] == "accept")
    return {
        "tau": tau, "f_hz": f_hz,
        "n_in": len(probes), "accepted_in": accepted,
        "accept_rate": accepted / len(probes),
        "accept_rate_wilson": wilson(accepted, len(probes)),
        "response_correct_on_accepts": correct,
        "response_accuracy_on_accepted": correct / accepted if accepted else None,
        "n_random": len(random_fields), "false_accepts": false_accepts,
        "false_accept_rate": false_accepts / len(random_fields),
        "false_accept_rate_wilson": wilson(false_accepts, len(random_fields)),
    }


def run_science():
    bubble = Bubble(seed=42, cal_seed=11)
    observer = Observer(bubble, sigma=0.05, seed=42)
    observer.measure_routing(n_rep=40)
    observer.measure_gate(n_in=100, n_ood=100)
    observer.measure_frequency(n_per=100)
    observer.measure_injection(n=100)

    # The user-review flag is simulated only to exercise the toy gate. This
    # script does not obtain or imply any real human review or authorization.
    calibrator = Calibrator(bubble)
    out_before, fail_before = calibrator.calibrate(observer.reports)
    bubble.set_review_signoff(True)
    out_after, fail_after = calibrator.calibrate(observer.reports)

    # Independent post-calibration assessment: same held-out data compare the
    # pre-calibration assumption and the locked calibration. It is not used to
    # choose or revise the calibration.
    split_rng = random.Random(404)
    labels = [i % len(bubble.system.RESPONSE_NAMES) for i in range(200)]
    split_rng.shuffle(labels)
    probes = [noisy(bubble.system.patterns[label], 0.15, split_rng)
              for label in labels]
    random_fields = [rand_field(bubble.system.n, split_rng) for _ in range(200)]
    pre_tau, pre_freq = bubble.assumed_tau, bubble.assumed_freq_hz
    pre_eval = evaluate_assumed(bubble, probes, labels, random_fields,
                                pre_tau, pre_freq)
    applied = False
    if fail_after is None:
        applied = calibrator.apply(out_after)
    post_eval = evaluate_assumed(
        bubble, probes, labels, random_fields,
        bubble.assumed_tau, bubble.assumed_freq_hz)

    sweep = full_sweep()
    opt = optimise(Bubble(seed=42, cal_seed=11))
    code_files = sorted(str(path) for path in pathlib.Path(".").glob("*.py"))
    raw_payload = {
        "package": "world-projection-3x3",
        "version": "0.2.0-review-candidate",
        "data_kind": "synthetic",
        "environment": {"python": platform.python_version()},
        "protocol": {
            "bubble_geometry_seed": 42,
            "internal_gate_calibration_seed": 11,
            "observer_seed": 42,
            "assumed_model_held_out_seed": 404,
            "assumed_model_held_out_n": 200,
            "assumed_model_labels_balanced_across": 4,
            "optimizer_split_seeds": DEFAULT_SPLIT_SEEDS,
            "optimizer_world_seeds": DEFAULT_WORLD_SEEDS,
            "optimizer_split_sizes": {"train": 100, "calibration": 100,
                                      "test": 100},
            "optimizer_search_grid": {
                "tau": "0.00..1.00 step 0.01",
                "frequency_hz": [0.25, 1.2, 7.0, 10.0]},
        },
        "calibration": {
            "simulated_review_flag_not_human_review": True,
            "refused_before_flag": (fail_before.to_dict()
                                     if fail_before else None),
            "proposal": out_after,
            "refusal_after_flag": (fail_after.to_dict() if fail_after else None),
            "applied_to_assumed_model": applied,
            "held_out_before": pre_eval,
            "held_out_after": post_eval,
            "held_out_seed": 404,
            "held_out_used_for_selection": False,
        },
        "sweep": sweep,
        "optimizer": opt,
        "observer_reports": [report.to_dict() for report in observer.reports],
        "headline_allowed": headline_allowed("synthetic", 1.0),
    }
    payload = json_safe(raw_payload)
    hashes = code_hashes(code_files)
    payload["code_sha256"] = hashes
    payload["passport_seal"] = seal(payload, code_files)
    return payload


def main(output_path="science-results.json"):
    payload = run_science()
    output = pathlib.Path(output_path)
    output.write_text(json.dumps(payload, sort_keys=True, indent=2,
                                 ensure_ascii=False, allow_nan=False) + "\n",
                      encoding="utf-8")
    print("world-projection-3x3 — reproducible synthetic evaluation")
    print("All probes and state are generated by this toy; this is not external validation.")
    print("Simulated review flag: true (not an actual human review or authorization)")
    print(f"Calibration applied to assumed model: {payload['calibration']['applied_to_assumed_model']}")
    print("Assumed-model held-out test (not used for selection):")
    print(f"  before: accept={payload['calibration']['held_out_before']['accept_rate']:.3f}, "
          f"response_accuracy_on_accepted={payload['calibration']['held_out_before']['response_accuracy_on_accepted']}")
    print(f"  after:  accept={payload['calibration']['held_out_after']['accept_rate']:.3f}, "
          f"response_accuracy_on_accepted={payload['calibration']['held_out_after']['response_accuracy_on_accepted']}")
    for label, row in payload["sweep"]["summary"].items():
        print(f"  sweep {label}: trajectory success mean={row['trajectory_success_mean']:.3f}, "
              f"range={row['trajectory_success_range']}")
    optimizer = payload["optimizer"]
    if optimizer["refused"]:
        print(f"Optimizer refused: {optimizer['reason']}")
    else:
        print(f"Optimizer selected on train: tau={optimizer['train_best']['tau']:.2f}, "
              f"frequency={optimizer['train_best']['f_hz']} Hz")
        print(f"  calibration constraints passed: {optimizer['calibration']['constraints_pass']}")
        print(f"  held-out trajectory success={optimizer['test']['end_to_end_success_rate']:.3f}, "
              f"false-accept={optimizer['test']['false_accept_rate']:.3f} "
              f"(95% Wilson {optimizer['test']['false_accept_rate_wilson'][1]:.3f}.."
              f"{optimizer['test']['false_accept_rate_wilson'][2]:.3f})")
        print(f"  frozen/oracle reference trajectory success="
              f"{optimizer['frozen_oracle_reference_test']['end_to_end_success_rate']:.3f}; "
              f"difference={optimizer['improvement_test']:.3f}")
    print(f"Headline allowed: {payload['headline_allowed']} (synthetic results are withheld)")
    print(f"Results JSON: {output.resolve()}")
    print(f"Passport seal: {payload['passport_seal']}")
    return payload


if __name__ == "__main__":
    destination = sys.argv[1] if len(sys.argv) > 1 else "science-results.json"
    main(destination)
